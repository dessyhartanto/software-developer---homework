// Program mencetak nama sebanyak 20 baris menggunakan for loop
for (var i = 1; i <= 20; i++) {
    console.log("I'm Steve"); // ganti "Steve" dengan namamu sendiri
}

// Program menampilkan urutan angka dari 1 sampai 20
for (var i = 1; i <= 20; i++) {
    console.log(i);
}

// Program menampilkan urutan angka 1-20 dalam satu baris
var hasil = '';
for (var i = 1; i <= 20; i++) {
    hasil += i + ' ';
}
console.log(hasil);

